class Main {
    public static void main(String[] args) {
        int operand1 = 40;
        int operand2 = 50;
        
        // SUM: 
        System.out.println("SUM: " + (operand1 + operand2));
        
        // DIFFERENCE:
        System.out.println("DIFFERENCE: " + (operand1 - operand2));
        
        // EXPAND:
        System.out.println("EXPAND: " + (operand1 * operand2));
        
        // DIVISION:
        System.out.println("DIVISION: " + (operand1 / operand2));
        
        
        /*output:
        SUM: 90
        DIFFERENCE: -10
        EXPAND: 2000
        DIVISION: 0*/
    }
}
